function generateQuestions(topicId: string, count: number, baseQuestions: Question[]): Question[] {
  const questions: Question[] = [];

  for (let i = 0; i < count; i++) {
    const baseIndex = i % baseQuestions.length;
    const base = baseQuestions[baseIndex];

    questions.push({
      ...base,
      id: `${topicId}-${i + 1}`,
      topicId,
      content: `${base.content}`,
      year: 2020 + (i % 5),
    });
  }

  return questions;
}

